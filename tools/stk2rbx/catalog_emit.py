def build_catalog(repo_root: Path) -> dict[str, list[dict[str, Any]]]:
    menu_manifest_path = repo_root / "assets" / "gui" / "menu" / "roblox_assets.json"
    menu_assets: dict[str, str] = {}
    if menu_manifest_path.is_file():
        menu_assets = json.loads(menu_manifest_path.read_text(encoding="utf-8")).get("assets", {})

    tracks: list[dict[str, Any]] = []
    tracks_dir = repo_root / "assets" / "tracks"
    if tracks_dir.is_dir():
        for manifest_path in sorted(tracks_dir.glob("*/roblox_assets.json")):
            track_dir = manifest_path.parent
            track_id = track_dir.name
            doc = json.loads(manifest_path.read_text(encoding="utf-8"))
            if not doc.get("track_id") or not doc.get("textures"):
                continue
            meta = TRACK_METADATA.get(track_id)
            if not meta:
                continue
            tracks.append(
                {
                    "id": track_id,
                    "name": meta["name"],
                    "designer": meta["designer"],
                    "defaultLaps": int(meta["defaultLaps"]),
                    "screenshotId": menu_assets.get(meta["screenshotAssetKey"], ""),
                    "playable": True,
                }
            )

    karts: list[dict[str, Any]] = []
    karts_dir = repo_root / "assets" / "karts"
    if karts_dir.is_dir():
        for manifest_path in sorted(karts_dir.glob("*/roblox_assets.json")):
            kart_dir = manifest_path.parent
            kart_id = kart_dir.name
            doc = json.loads(manifest_path.read_text(encoding="utf-8"))
            parts = doc.get("parts", {})
            if not doc.get("kartId") or not any(p.get("meshId") for p in parts.values()):
                continue
            meta = KART_METADATA.get(kart_id)
            if not meta:
                continue
            karts.append(
                {
                    "id": kart_id,
                    "name": str(doc.get("kartName") or meta["name"]),
                    "kartType": str(doc.get("kartType") or meta["kartClass"]),
                    "kartClass": str(doc.get("kartType") or meta["kartClass"]),
                    "iconId": str(doc.get("iconId") or meta.get("iconId") or ""),
                    "playable": True,
                }
            )

    return {"tracks": tracks, "karts": karts}


def format_luau(catalog: dict[str, list[dict[str, Any]]]) -> str:
    lines = [
        "--!strict",
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        "-- Generated by tools/stk2rbx/catalog_emit.py from assets/*/roblox_assets.json (STK 1.5).",
        "",
        "export type TrackEntry = {",
        "\tid: string,",
        "\tname: string,",
        "\tdesigner: string,",
        "\tdefaultLaps: number,",
        "\tscreenshotId: string,",
        "\tplayable: boolean,",
        "}",
        "",
        "export type KartEntry = {",
        "\tid: string,",
        "\tname: string,",
        "\tkartType: string,",
        "\ticonId: string,",
        "\tplayable: boolean,",
        "}",
        "",
        "local CatalogData = {",
        "\ttracks = {",
    ]
    for t in catalog["tracks"]:
        lines.extend(
            [
                "\t\t{",
                f'\t\t\tid = "{t["id"]}",',
                f'\t\t\tname = "{t["name"]}",',
                f'\t\t\tdesigner = "{t["designer"]}",',
                f'\t\t\tdefaultLaps = {t["defaultLaps"]},',
                f'\t\t\tscreenshotId = "{t["screenshotId"]}",',
                f'\t\t\tplayable = {"true" if t["playable"] else "false"},',
                "\t\t},",
            ]
        )
    lines.append("\t} :: { TrackEntry },")
    lines.append("\tkarts = {")
    for k in catalog["karts"]:
        lines.extend(
            [
                "\t\t{",
                f'\t\t\tid = "{k["id"]}",',
                f'\t\t\tname = "{k["name"]}",',
                f'\t\t\tkartType = "{k["kartType"]}",',
                f'\t\t\ticonId = "{k["iconId"]}",',
                f'\t\t\tplayable = {"true" if k["playable"] else "false"},',
                "\t\t},",
            ]
        )
    lines.extend(
        [
            "\t} :: { KartEntry },",
            "}",
            "",
            "return CatalogData",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    repo_root = Path(__file__).resolve().parents[2]
    catalog = build_catalog(repo_root)
    out_path = repo_root / "src" / "shared" / "menu" / "CatalogData.lua"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(format_luau(catalog), encoding="utf-8")
    print(f"Emitted {out_path} ({len(catalog['tracks'])} tracks, {len(catalog['karts'])} karts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
