REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_SPEC_PATH = REPO_ROOT / "tools" / "arena_spec.json"
DEFAULT_LUAU_OUT = REPO_ROOT / "src" / "shared" / "track" / "GreyboxArenaData.lua"
DEFAULT_STK_TRACK_DIR = REPO_ROOT / "build" / "stk_tracks" / "openkart_arena"


def load_arena_spec(spec_path: Path = DEFAULT_SPEC_PATH) -> dict[str, Any]:
    return json.loads(spec_path.read_text(encoding="utf-8"))


def _write_solid_png(path: Path, rgb: tuple[int, int, int], alpha: int = 255) -> None:
    """Write a minimal valid 4x4 RGBA PNG fallback when local STK textures are absent."""
    w, h = 4, 4
    row = bytes([0]) + bytes([rgb[0], rgb[1], rgb[2], alpha]) * w
    raw = row * h

    def chunk(tag: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(tag + data) & 0xFFFFFFFF
        return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", crc)

    ihdr = struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)
    png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    path.write_bytes(png)


def _escape_lua_str(val: str) -> str:
    return val.replace("\\", "\\\\").replace('"', '\\"')


def emit_roblox_luau(spec: dict[str, Any], out_luau_path: Path = DEFAULT_LUAU_OUT) -> Path:
    """Emit src/shared/track/GreyboxArenaData.lua from canonical STK metric spec."""
    lines: list[str] = [
        "--!strict",
        "-- src/shared/track/GreyboxArenaData.lua",
        "-- SPDX-License-Identifier: GPL-3.0-or-later",
        "-- AUTO-GENERATED by tools/stk2rbx/arena_emit.py from tools/arena_spec.json — DO NOT EDIT BY HAND.",
        "",
        "export type ArenaBoxSpec = {",
        "\tname: string,",
        "\tisPrimary: boolean,",
        "\tpos: { number },",
        "\tsize: { number },",
        "\trotDeg: { number },",
        "\tmaterial: string,",
        "\tcolorRgb: { number },",
        "\trbxMaterial: string,",
        "\tcanCollide: boolean,",
        "\ttransparency: number,",
        "\tlabel: string?,",
        "\tlabelY: number?,",
        "\tlabelColorRgb: { number }?,",
        "}",
        "",
        "export type ArenaDrivelinePoint = {",
        "\tx: number,",
        "\tz: number,",
        "}",
        "",
        "export type ArenaBounds = {",
        "\tminX: number,",
        "\tmaxX: number,",
        "\tminZ: number,",
        "\tmaxZ: number,",
        "\trange: number,",
        "}",
        "",
        "export type ArenaSpec = {",
        '\ttrackId: string,',
        "\tplaneSizeStuds: number,",
        "\tplaneThicknessStuds: number,",
        "\tgridSpacingStuds: number,",
        "\tboxes: { ArenaBoxSpec },",
        "\tdrivelineQuadCenters: { ArenaDrivelinePoint },",
        "\tminimapBounds: ArenaBounds,",
        "}",
        "",
        "local function deepFreeze<T>(tbl: T): T",
        '\tif type(tbl) == "table" and not table.isfrozen(tbl :: any) then',
        "\t\tfor _, v in tbl :: any do",
        '\t\t\tif type(v) == "table" then',
        "\t\t\t\tdeepFreeze(v)",
        "\t\t\tend",
        "\t\tend",
        "\t\ttable.freeze(tbl :: any)",
        "\tend",
        "\treturn tbl",
        "end",
        "",
        "local GreyboxArenaData: ArenaSpec = {",
        f'\ttrackId = "{_escape_lua_str(spec["track_id"])}",',
        f'\tplaneSizeStuds = {spec["plane_size_m"]},',
        f'\tplaneThicknessStuds = {spec["plane_thickness_m"]},',
        f'\tgridSpacingStuds = {spec["grid_spacing_m"]},',
        "\tboxes = {",
    ]

    for box in spec["boxes"]:
        rx, ry, rz = stk_to_rbx_pos(box["pos"][0], box["pos"][1], box["pos"][2])
        sx, sy, sz = box["size"]
        ax, ay, az = box.get("rot_deg", [0.0, 0.0, 0.0])
        cr, cg, cb = box["color_rgb"]
        is_primary = "true" if box.get("is_primary", False) else "false"
        can_collide = "true" if box.get("can_collide", True) else "false"
        transparency = box.get("transparency", 0.0)

        lines.extend([
            "\t\t{",
            f'\t\t\tname = "{_escape_lua_str(box["name"])}",',
            f"\t\t\tisPrimary = {is_primary},",
            f"\t\t\tpos = {{ {rx}, {ry}, {rz} }},",
            f"\t\t\tsize = {{ {sx}, {sy}, {sz} }},",
            f"\t\t\trotDeg = {{ {ax}, {ay}, {az} }},",
            f'\t\t\tmaterial = "{_escape_lua_str(box["material"])}",',
            f"\t\t\tcolorRgb = {{ {cr}, {cg}, {cb} }},",
            f'\t\t\trbxMaterial = "{_escape_lua_str(box["rbx_material"])}",',
            f"\t\t\tcanCollide = {can_collide},",
            f"\t\t\ttransparency = {transparency},",
        ])
        if box.get("label"):
            lr, lg, lb = box["label_color_rgb"]
            lines.extend([
                f'\t\t\tlabel = "{_escape_lua_str(box["label"])}",',
                f'\t\t\tlabelY = {box["label_y"]},',
                f"\t\t\tlabelColorRgb = {{ {lr}, {lg}, {lb} }},",
            ])
        lines.append("\t\t},")

    half = 0.5 * float(spec["plane_size_m"])
    q_edges = [-half, -0.5 * half, 0.0, 0.5 * half, half]
    lines.extend([
        "\t},",
        "\tdrivelineQuadCenters = {",
    ])
    for qi in range(len(q_edges) - 1):
        z_mid = 0.5 * (q_edges[qi] + q_edges[qi + 1])
        lines.append(f"\t\t{{ x = 0.0, z = {z_mid} }},")
    lines.extend([
        "\t},",
        "\tminimapBounds = {",
        f"\t\tminX = {-half},",
        f"\t\tmaxX = {half},",
        f"\t\tminZ = {-half},",
        f"\t\tmaxZ = {half},",
        f"\t\trange = {float(spec['plane_size_m'])},",
        "\t},",
        "}",
        "",
        "return deepFreeze(GreyboxArenaData)",
        "",
    ])

    out_luau_path.parent.mkdir(parents=True, exist_ok=True)
    out_luau_path.write_text("\n".join(lines), encoding="utf-8")
    return out_luau_path


def _find_default_textures_dir() -> Path | None:
    candidates = [
        Path(r"C:\Program Files\SuperTuxKart 1.5\data\tracks\sandtrack"),
        Path(r"C:\dev\stk-assets\tracks\sandtrack"),
    ]
    for c in candidates:
        if c.is_dir():
            return c
    return None


def emit_stk_track(
    spec: dict[str, Any],
    out_dir: Path = DEFAULT_STK_TRACK_DIR,
    textures_dir: Path | None = None,
) -> Path:
    """Emit a self-contained runnable STK 1.5 track directory from arena_spec.json."""
    out_dir.mkdir(parents=True, exist_ok=True)
    track_id = str(spec["track_id"])
    track_name = str(spec["track_name"])
    model_name = f"{track_id}_track.spm"

    grouped_verts: dict[str, list[SpmVertex]] = defaultdict(list)
    grouped_idxs: dict[str, list[int]] = defaultdict(list)
    mat_colors: dict[str, tuple[int, int, int]] = {}

    for box in spec["boxes"]:
        mat = str(box["material"])
        rgb = (int(box["color_rgb"][0]), int(box["color_rgb"][1]), int(box["color_rgb"][2]))
        mat_colors.setdefault(mat, rgb)
        b_verts, b_idxs = build_box_geometry(
            box["pos"],
            box["size"],
            box.get("rot_deg", [0.0, 0.0, 0.0]),
            color_rgb=None,
        )
        base = len(grouped_verts[mat])
        grouped_verts[mat].extend(b_verts)
        grouped_idxs[mat].extend(base + idx for idx in b_idxs)

    submeshes: list[SpmSubmesh] = []
    for mat_name, verts in grouped_verts.items():
        submeshes.append(SpmSubmesh(texture_1=mat_name, vertices=verts, indices=grouped_idxs[mat_name]))
    write_spmn(out_dir / model_name, submeshes)

    # track.xml
    track_xml = "\n".join([
        '<?xml version="1.0"?>',
        "<track",
        f'  name="{track_name}"',
        '  version="7"',
        '  groups="standard"',
        '  designer="OpenKart"',
        '  smooth-normals="false"',
        '  default-number-of-laps="3"',
        '  reverse="N"',
        '  clouds="N"',
        '  is-during-day="Y"',
        '  shadows="N"',
        "/>",
        "",
    ])
    (out_dir / "track.xml").write_text(track_xml, encoding="utf-8")

    # materials.xml (matching sandtrack/materials.xml gameplay properties)
    mat_lines = ['<?xml version="1.0"?>', "<materials>"]
    needed_textures: set[str] = set()
    for m in spec["materials"]:
        needed_textures.add(str(m["name"]))
        attrs = [f'name="{m["name"]}"']
        if m.get("shader"):
            attrs.append(f'shader="{m["shader"]}"')
        if m.get("ignore"):
            attrs.append('ignore="Y"')
        if m.get("high_adhesion"):
            attrs.append('high-adhesion="Y"')
        if "slowdown_time" in m:
            attrs.append(f'slowdown-time="{m["slowdown_time"]:.2f}"')
        if "max_speed" in m:
            attrs.append(f'max-speed="{m["max_speed"]:.2f}"')
        if m.get("reset"):
            attrs.append('reset="Y"')
        if m.get("collision_detect"):
            attrs.append('collision-detect="Y"')
        if m.get("collision_reaction"):
            attrs.append(f'collision-reaction="{m["collision_reaction"]}"')
        if m.get("surface"):
            attrs.append('surface="Y"')
        if m.get("falling_effect"):
            attrs.append('falling-effect="Y"')
        if m.get("water_splash"):
            attrs.append('water-splash="Y"')
        mat_lines.append(f"  <material {' '.join(attrs)}/>")
    mat_lines.extend(["</materials>", ""])
    (out_dir / "materials.xml").write_text("\n".join(mat_lines), encoding="utf-8")

    # quads.xml (full 512x512m coverage in 4 slices so dist_to_sector == 0 everywhere in arena)
    half = 0.5 * float(spec["plane_size_m"])
    q_edges = [-half, -0.5 * half, 0.0, 0.5 * half, half]
    quad_lines = [
        '<?xml version="1.0"?>',
        "<quads>",
        '  <height-testing min="-10.000000" max="30.000000"/>',
        f'  <quad p0="{-half:.3f} 0.000 {q_edges[0]:.3f}" p1="{half:.3f} 0.000 {q_edges[0]:.3f}" p2="{half:.3f} 0.000 {q_edges[1]:.3f}" p3="{-half:.3f} 0.000 {q_edges[1]:.3f}"/>',
    ]
    for qi in range(1, len(q_edges) - 1):
        z1 = q_edges[qi + 1]
        prev = qi - 1
        quad_lines.append(
            f'  <quad p0="{prev}:3" p1="{prev}:2" p2="{half:.3f} 0.000 {z1:.3f}" p3="{-half:.3f} 0.000 {z1:.3f}"/>'
        )
    quad_lines.extend(["</quads>", ""])
    (out_dir / "quads.xml").write_text("\n".join(quad_lines), encoding="utf-8")

    # graph.xml
    graph_xml = "\n".join([
        '<?xml version="1.0"?>',
        "<graph>",
        f'  <node-list from-quad="0" to-quad="{len(q_edges) - 2}"/>',
        f'  <edge-loop from="0" to="{len(q_edges) - 2}"/>',
        "</graph>",
        "",
    ])
    (out_dir / "graph.xml").write_text(graph_xml, encoding="utf-8")

    # scene.xml
    sx, sy, sz = spec["spawn"]["pos"]
    sh = spec["spawn"]["heading_deg"]
    scene_xml = "\n".join([
        '<?xml version="1.0"?>',
        "<scene>",
        f'  <track model="{model_name}" x="0" y="0" z="0"/>',
        f'  <start position="0" xyz="{sx} {sy} {sz}" h="{sh}"/>',
        '  <sun xyz="100.0 250.0 150.0" sun-diffuse="255 245 225" ambient="180 185 195"/>',
        '  <camera far="2500.0"/>',
        "  <checks>",
        '    <check-lap kind="lap" same-group="0" other-ids="1"/>',
        '    <check-line kind="activate" other-ids="0" p1="-256.0 0.0 128.0" p2="256.0 0.0 128.0" same-group="1"/>',
        "  </checks>",
        "</scene>",
        "",
    ])
    (out_dir / "scene.xml").write_text(scene_xml, encoding="utf-8")

    # Copy or synthesize required textures locally inside out_dir
    tex_src = textures_dir if textures_dir is not None else _find_default_textures_dir()
    for tex_name in sorted(needed_textures):
        dst = out_dir / tex_name
        src_file = (tex_src / tex_name) if tex_src is not None else None
        if src_file is not None and src_file.is_file():
            shutil.copy2(src_file, dst)
        else:
            rgb = mat_colors.get(tex_name, (140, 140, 140))
            alpha = 150 if tex_name == "oasis-water.png" else 255
            _write_solid_png(dst, rgb, alpha=alpha)

    return out_dir


def main() -> None:
    parser = argparse.ArgumentParser(description="Emit Roblox Luau data and STK 1.5 test track from arena_spec.json")
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC_PATH)
    parser.add_argument("--luau-out", type=Path, default=DEFAULT_LUAU_OUT)
    parser.add_argument("--stk-out", type=Path, default=DEFAULT_STK_TRACK_DIR)
    parser.add_argument("--textures-dir", type=Path, default=None)
    args = parser.parse_args()

    spec = load_arena_spec(args.spec)
    luau_path = emit_roblox_luau(spec, args.luau_out)
    stk_dir = emit_stk_track(spec, args.stk_out, args.textures_dir)
    print(f"Emitted Roblox arena data -> {luau_path}")
    print(f"Emitted STK track        -> {stk_dir}")


if __name__ == "__main__":
    main()
